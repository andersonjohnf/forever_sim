// One-off generator: freezes the defaults a deployed build gave every spec into
// src/app/legacy-defaults.ts, the table saves from before `following` migrate by
// (docs/architecture.md "Following the defaults"; src/app/follow-defaults.ts legacyFollowing).
//
// The table must never follow today's defaults: a save that holds an old default has to keep being
// recognized after the default changes. So this reads the source at a fixed commit, not the working
// tree: it extracts that commit's src/ into .cache/legacy-defaults/<ref>/, runs a dump there with
// vitest (the same TypeScript the app ran), and writes the module from the dump.
//
//   node scripts/freeze-legacy-defaults.mjs            # ee171d2a, the last build deployed before `following`
//   node scripts/freeze-legacy-defaults.mjs <ref>      # another commit (only to check; the table stays ee171d2a's)
//
// For each spec: the class's default race, the default talent build, and for every race the class
// can be in Forever (races.json `classes.forever`) the default gear (defaultConfig, normalized, as
// `defaultGearFor` gives it) and v1's pick (the pre-raid lists alone, `preRaidListGear`), as
// [itemId, enchantId?] per slot. Races with the same gear share one set.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REF = process.argv[2] ?? 'ee171d2a'
const OUT = join(ROOT, 'src/app/legacy-defaults.ts')

const commit = execFileSync('git', ['rev-parse', '--short=8', `${REF}^{commit}`], { cwd: ROOT }).toString().trim()
const dir = join(ROOT, '.cache/legacy-defaults', commit)
rmSync(dir, { recursive: true, force: true })
mkdirSync(dir, { recursive: true })
const archive = execFileSync('git', ['archive', commit, 'src', 'tsconfig.json', 'tsconfig.app.json', 'tsconfig.node.json'], { cwd: ROOT, maxBuffer: 1 << 30 })
execFileSync('tar', ['-x', '-C', dir], { input: archive })
if (!existsSync(join(dir, 'node_modules'))) symlinkSync(join(ROOT, 'node_modules'), join(dir, 'node_modules'))

writeFileSync(
  join(dir, 'vitest.freeze.config.mjs'),
  `import { fileURLToPath, URL } from 'node:url'
export default { resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } }, test: { include: ['freeze.test.ts'], testTimeout: 600000 } }
`,
)
writeFileSync(
  join(dir, 'freeze.test.ts'),
  `import { test } from 'vitest'
import { writeFileSync } from 'node:fs'
import { defaultConfig, preRaidListGear } from '@/sim/defaults'
import { normalizeConfig } from '@/sim/config/normalize'
import { SPEC_IDS, SPEC_META } from '@/sim/specs'
import races from '@/data/races/races.json'

test('freeze', () => {
  const out: Record<string, unknown> = {}
  for (const spec of SPEC_IDS) {
    const { classId } = SPEC_META[spec]
    const base = defaultConfig(spec)
    const byRace: Record<string, unknown> = {}
    for (const race of (races as any).races.filter((r: any) => r.classes.forever.includes(classId)).map((r: any) => r.id)) {
      const config = defaultConfig(spec, race)
      byRace[race] = {
        gear: normalizeConfig(config).config.gear,
        list: normalizeConfig({ ...config, gear: preRaidListGear(spec, race) }).config.gear,
      }
    }
    out[spec] = { race: base.race, talents: base.talents, byRace }
  }
  writeFileSync(process.env.FREEZE_OUT!, JSON.stringify(out))
})
`,
)
const dump = join(dir, 'freeze.json')
execFileSync('npx', ['vitest', 'run', '--config', 'vitest.freeze.config.mjs', '--root', '.'], {
  cwd: dir,
  env: { ...process.env, FREEZE_OUT: dump },
  stdio: 'inherit',
})
const specs = JSON.parse(readFileSync(dump, 'utf8'))

/** A slot as a tuple: [itemId] or [itemId, enchantId]. */
const q = (value) => `'${value}'`
const tuple = (entry) => (entry.enchantId ? `[${entry.itemId}, ${q(entry.enchantId)}]` : `[${entry.itemId}]`)
const compact = (gear) => `{ ${Object.entries(gear).map(([slot, entry]) => `${slot}: ${tuple(entry)}`).join(', ')} }`

const lines = []
for (const [spec, { race, talents, byRace }] of Object.entries(specs)) {
  const sets = []
  const index = (gear) => {
    const text = compact(gear)
    let i = sets.indexOf(text)
    if (i < 0) i = sets.push(text) - 1
    return i
  }
  const races = Object.entries(byRace).map(([r, { gear, list }]) => `${q(r)}: [${index(gear)}, ${index(list)}]`)
  lines.push(
    `  ${q(spec)}: {`,
    `    race: ${q(race)},`,
    `    talents: ${q(talents)},`,
    `    sets: [`,
    ...sets.map((s) => `      ${s},`),
    `    ],`,
    `    races: { ${races.join(', ')} },`,
    `  },`,
  )
}

writeFileSync(
  OUT,
  `// Generated by scripts/freeze-legacy-defaults.mjs from ${commit}, the last build deployed before saves
// said what follows the defaults. Don't edit it, and don't regenerate it from a newer commit: it's
// frozen on purpose (docs/architecture.md "Following the defaults"), so a save holding these defaults
// keeps migrating however the defaults change later.
import type { GearSlot, SpecId } from '@/sim'

/** A slot's item and enchant, as [itemId] or [itemId, enchantId]. */
export type LegacyEntry = readonly [number] | readonly [number, string]

/** One spec's defaults at ${commit}. */
export interface LegacySpecDefaults {
  /** The class's default race. */
  race: string
  /** The default talent build. */
  talents: string
  /** The distinct gear sets, normalized as a loaded setup holds them. */
  sets: readonly Partial<Record<GearSlot, LegacyEntry>>[]
  /** Per race the class can be: [its default gear, v1's pick (the pre-raid lists alone)], as indices into \`sets\`. */
  races: Readonly<Record<string, readonly [number, number]>>
}

export const LEGACY_COMMIT = ${q(commit)}

export const LEGACY_DEFAULTS: Readonly<Partial<Record<SpecId, LegacySpecDefaults>>> = {
${lines.join('\n')}
}
`,
)
console.log(`Wrote ${OUT} from ${commit}`)
